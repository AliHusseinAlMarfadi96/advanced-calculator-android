  static String text(String key, AppLanguage language) {
    final map = language == AppLanguage.ar ? _ar : _en;
    return map[key] ?? key;
  }

  static String failure(EvalFailure failure, AppLanguage language) {
    switch (failure) {
      case EvalFailure.divideByZero:
        return text('error.divideByZero', language);
      case EvalFailure.domain:
        return text('error.domain', language);
      case EvalFailure.syntax:
        return text('error.syntax', language);
    }
  }
